// Expo config plugin: make the app trust the API server's self-signed certificate(s).
// The certificates are trusted ONLY for the listed hosts, on top of the normal system CAs.
// Several certs are supported because the server presents a different one when the client
// connects by IP without SNI (Android never sends SNI for IP addresses).
// Android: network-security-config. Cleartext stays allowed for LAN development servers.
// iOS: a category on React Native's RCTHTTPRequestHandler (the NSURLSession delegate behind
// fetch/XHR) that evaluates server trust for the listed hosts with the certs as extra anchors.
const fs = require('fs');
const path = require('path');
const { IOSConfig, withAndroidManifest, withDangerousMod, withXcodeProject } = require('expo/config-plugins');

const IOS_FILE = 'ServerCertTrust.m';

// PEM file(s) -> base64 DER strings (one per certificate in each file).
function derBase64(root, files) {
  return files.flatMap((file) => {
    const pem = fs.readFileSync(path.join(root, file), 'utf8');
    const blocks = [...pem.matchAll(/-----BEGIN CERTIFICATE-----([\s\S]*?)-----END CERTIFICATE-----/g)].map((m) => m[1].replace(/\s+/g, ''));
    if (!blocks.length) throw new Error(`withServerCert: no certificate found in ${file}`);
    return blocks;
  });
}

const objcStrings = (list) => list.map((s) => `@"${s}"`).join(', ');

function iosSource(hosts, certs) {
  return `// Generated by plugins/withServerCert.js. Do not edit; change app.json and run prebuild.
#import <Foundation/Foundation.h>
#import <Security/Security.h>
#import <React/RCTHTTPRequestHandler.h>

static NSArray *ServerCertAnchors(void)
{
  static NSArray *anchors;
  static dispatch_once_t once;
  dispatch_once(&once, ^{
    NSMutableArray *list = [NSMutableArray array];
    for (NSString *b64 in @[ ${objcStrings(certs)} ]) {
      NSData *der = [[NSData alloc] initWithBase64EncodedString:b64 options:0];
      SecCertificateRef cert = der ? SecCertificateCreateWithData(NULL, (__bridge CFDataRef)der) : NULL;
      if (cert) [list addObject:(__bridge_transfer id)cert];
    }
    anchors = list;
  });
  return anchors;
}

@implementation RCTHTTPRequestHandler (ServerCertTrust)

- (void)URLSession:(NSURLSession *)session
    didReceiveChallenge:(NSURLAuthenticationChallenge *)challenge
      completionHandler:(void (^)(NSURLSessionAuthChallengeDisposition, NSURLCredential *))completionHandler
{
  NSURLProtectionSpace *space = challenge.protectionSpace;
  SecTrustRef trust = space.serverTrust;
  if (![space.authenticationMethod isEqualToString:NSURLAuthenticationMethodServerTrust] || !trust ||
      ![@[ ${objcStrings(hosts)} ] containsObject:space.host]) {
    completionHandler(NSURLSessionAuthChallengePerformDefaultHandling, nil);
    return;
  }
  // Trust the bundled certs in addition to (not instead of) the system CAs.
  SecTrustSetAnchorCertificates(trust, (__bridge CFArrayRef)ServerCertAnchors());
  SecTrustSetAnchorCertificatesOnly(trust, false);
  if (SecTrustEvaluateWithError(trust, NULL)) {
    completionHandler(NSURLSessionAuthChallengeUseCredential, [NSURLCredential credentialForTrust:trust]);
  } else {
    completionHandler(NSURLSessionAuthChallengeCancelAuthenticationChallenge, nil);
  }
}

@end
`;
}

function withServerCertIos(config, files, hosts) {
  config = withDangerousMod(config, [
    'ios',
    async (cfg) => {
      const root = cfg.modRequest.projectRoot;
      const dir = path.join(cfg.modRequest.platformProjectRoot, IOSConfig.XcodeUtils.getProjectName(root));
      fs.writeFileSync(path.join(dir, IOS_FILE), iosSource(hosts, derBase64(root, files)));
      return cfg;
    },
  ]);
  return withXcodeProject(config, (cfg) => {
    const name = IOSConfig.XcodeUtils.getProjectName(cfg.modRequest.projectRoot);
    const filepath = `${name}/${IOS_FILE}`;
    if (!cfg.modResults.hasFile(filepath)) {
      IOSConfig.XcodeUtils.addBuildSourceFileToGroup({ filepath, groupName: name, project: cfg.modResults });
    }
    return cfg;
  });
}

function networkConfigXml(hosts, rawNames) {
  const domains = hosts.map((h) => `    <domain includeSubdomains="false">${h}</domain>`).join('\n');
  const anchors = rawNames.map((n) => `      <certificates src="@raw/${n}" />`).join('\n');
  return `<?xml version="1.0" encoding="utf-8"?>
<network-security-config>
  <base-config cleartextTrafficPermitted="true">
    <trust-anchors>
      <certificates src="system" />
    </trust-anchors>
  </base-config>
  <domain-config>
${domains}
    <trust-anchors>
${anchors}
      <certificates src="system" />
    </trust-anchors>
  </domain-config>
</network-security-config>
`;
}

module.exports = function withServerCert(config, { certPaths = [], certPath, hosts = [] } = {}) {
  const files = certPaths.length ? certPaths : certPath ? [certPath] : [];
  const rawNames = files.map((_, i) => `server_cert_${i}`);
  if (files.length && hosts.length) config = withServerCertIos(config, files, hosts);

  config = withDangerousMod(config, [
    'android',
    async (cfg) => {
      const root = cfg.modRequest.projectRoot;
      const res = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src', 'main', 'res');
      fs.mkdirSync(path.join(res, 'raw'), { recursive: true });
      fs.mkdirSync(path.join(res, 'xml'), { recursive: true });
      // Remove certs from earlier builds so only the configured ones ship.
      for (const f of fs.readdirSync(path.join(res, 'raw'))) {
        if (/^server_cert.*\.pem$/.test(f)) fs.unlinkSync(path.join(res, 'raw', f));
      }
      files.forEach((file, i) => fs.copyFileSync(path.join(root, file), path.join(res, 'raw', `${rawNames[i]}.pem`)));
      fs.writeFileSync(path.join(res, 'xml', 'network_security_config.xml'), networkConfigXml(hosts, rawNames));
      return cfg;
    },
  ]);

  return withAndroidManifest(config, (cfg) => {
    const app = cfg.modResults.manifest.application?.[0];
    if (app) app.$['android:networkSecurityConfig'] = '@xml/network_security_config';
    return cfg;
  });
};
